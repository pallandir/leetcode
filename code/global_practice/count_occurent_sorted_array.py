def count_occurence(array, target):
    left, right = 0, len(array) - 1
    first_occ, second_occ = -1, -1
    while left <= right:
        mid = (left + right) // 2
        if array[mid] == target:
            first_occ = mid
            right = mid - 1
        elif array[mid] < target:
            left = mid + 1
        else:
            right = mid - 1
    if first_occ == -1:
        return 0

    left, right = 0, len(array) - 1
    while left <= right:
        mid = (left + right) // 2
        if array[mid] == target:
            second_occ = mid
            left = mid + 1
        elif array[mid] < target:
            left = mid + 1
        else:
            right = mid - 1
    return second_occ - first_occ + 1


